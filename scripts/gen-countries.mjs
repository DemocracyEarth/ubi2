// Generate the ISO 3166-1 alpha-3 -> (flag, short English name) tables for both on-chain stacks.
// Deterministic codegen: alpha-3->alpha-2 from i18n-iso-countries, short names from Intl.DisplayNames.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const iso = require("i18n-iso-countries");

const dn = new Intl.DisplayNames(["en"], { type: "region" });
const flagOf = (a2) =>
  String.fromCodePoint(0x1f1e6 + a2.charCodeAt(0) - 65, 0x1f1e6 + a2.charCodeAt(1) - 65);

const rows = [];
for (const a3 of Object.keys(iso.getAlpha3Codes())) {
  const a2 = iso.alpha3ToAlpha2(a3);
  if (!a2 || a2.length !== 2) continue;
  let name = dn.of(a2);
  if (!name || name === a2) name = iso.getName(a3, "en"); // fallback to ISO name
  if (!name) continue;
  name = name.replace(/&/g, "and").trim(); // XML-safe: no & in country names (no < or > occur)
  rows.push({ a3, a2, name, flag: flagOf(a2) });
}
rows.sort((x, y) => (x.a3 < y.a3 ? -1 : 1)); // sorted by alpha-3 (needed for lookup determinism)
console.log(`countries: ${rows.length}`);
console.log("spot:", ["ARG", "USA", "GBR", "KOR", "COD"].map((c) => {
  const r = rows.find((r) => r.a3 === c);
  return `${c}→${r.flag} ${r.name}`;
}).join("  "));
const longest = rows.reduce((a, b) => (b.name.length > a.name.length ? b : a));
console.log(`longest name: "${longest.name}" (${longest.name.length} chars)`);

// ---------- Rust: crates/rpc/src/poh_countries.rs ----------
const rustRows = rows
  .map((r) => `    (b"${r.a3}", "${r.flag}", ${JSON.stringify(r.name)}),`)
  .join("\n");
const rust = `//! ISO 3166-1 alpha-3 → (flag emoji, short English name). GENERATED by scripts/gen-countries.mjs.
//! Do not hand-edit. Used by the PoH NFT card renderer (\`poh_nft.rs\`) to show a human's nationality.

/// (alpha-3, flag emoji, short English name), sorted by alpha-3 for binary search.
static COUNTRIES: &[(&[u8; 3], &str, &str)] = &[
${rustRows}
];

/// Look up a nationality by its ISO 3166-1 alpha-3 code (e.g. \`b"ARG"\`). Returns \`(flag, name)\`
/// (e.g. \`("🇦🇷", "Argentina")\`), or \`None\` for an unknown/undisclosed code.
pub fn lookup(a3: &[u8; 3]) -> Option<(&'static str, &'static str)> {
    COUNTRIES
        .binary_search_by(|(code, _, _)| code[..].cmp(&a3[..]))
        .ok()
        .map(|i| (COUNTRIES[i].1, COUNTRIES[i].2))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn known_codes_resolve() {
        assert_eq!(lookup(b"ARG"), Some(("🇦🇷", "Argentina")));
        assert_eq!(lookup(b"USA").map(|(_, n)| n), Some("United States"));
        assert_eq!(lookup(b"PRT").map(|(f, _)| f), Some("🇵🇹"));
        assert_eq!(lookup(b"ZZZ"), None);
    }
    #[test]
    fn table_is_sorted_for_binary_search() {
        for w in COUNTRIES.windows(2) {
            assert!(w[0].0 < w[1].0, "table must be sorted by alpha-3");
        }
    }
}
`;

// ---------- Solidity: contracts/src/Countries.sol ----------
// Packed records sorted by alpha-3: [a3(3) | a2(2) | nameLen(1) | name(UTF-8 bytes)].
let hex = "";
for (const r of rows) {
  const nameBytes = Buffer.from(r.name, "utf8");
  hex += Buffer.from(r.a3, "ascii").toString("hex");
  hex += Buffer.from(r.a2, "ascii").toString("hex");
  hex += nameBytes.length.toString(16).padStart(2, "0");
  hex += nameBytes.toString("hex");
}
const sol = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

/// @title Countries
/// @notice ISO 3166-1 alpha-3 -> (flag emoji, short English name). GENERATED by
///         scripts/gen-countries.mjs from the canonical ISO source; do not hand-edit.
/// @dev Records are packed & sorted by alpha-3 as [a3(3) | a2(2) | nameLen(1) | name(UTF-8)].
///      \`get\` is a pure view helper (linear scan; no gas cost off-chain).
library Countries {
    bytes constant DATA =
        hex"${hex}";

    /// @notice Resolve an ISO 3166-1 alpha-3 code to its flag emoji + short English name.
    /// @return ok  Whether the code was found.
    /// @return flag The flag emoji (e.g. unicode AR -> Argentine flag), "" if not found.
    /// @return name The short English name (e.g. "Argentina"), "" if not found.
    function get(bytes3 a3) internal pure returns (bool ok, string memory flag, string memory name) {
        bytes memory d = DATA;
        uint256 i = 0;
        while (i < d.length) {
            uint8 len = uint8(d[i + 5]);
            if (d[i] == a3[0] && d[i + 1] == a3[1] && d[i + 2] == a3[2]) {
                bytes memory nm = new bytes(len);
                for (uint256 j = 0; j < len; j++) nm[j] = d[i + 6 + j];
                return (true, _flag(d[i + 3], d[i + 4]), string(nm));
            }
            i += 6 + len;
        }
        return (false, "", "");
    }

    /// @dev The flag emoji for an ISO alpha-2 pair = two Regional Indicator Symbols
    ///      (U+1F1E6 + (letter - 'A')), each 4 UTF-8 bytes F0 9F 87 (A6+idx).
    function _flag(bytes1 c0, bytes1 c1) private pure returns (string memory) {
        bytes memory f = new bytes(8);
        f[0] = 0xF0; f[1] = 0x9F; f[2] = 0x87; f[3] = bytes1(uint8(0xA6) + (uint8(c0) - 65));
        f[4] = 0xF0; f[5] = 0x9F; f[6] = 0x87; f[7] = bytes1(uint8(0xA6) + (uint8(c1) - 65));
        return string(f);
    }
}
`;

writeFileSync(process.argv[2] + "/crates/rpc/src/poh_countries.rs", rust);
writeFileSync(process.argv[2] + "/contracts/src/Countries.sol", sol);
console.log("Solidity DATA bytes:", hex.length / 2);
console.log("wrote crates/rpc/src/poh_countries.rs + contracts/src/Countries.sol");
